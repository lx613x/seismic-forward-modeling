function export_scores(cfg, plans, geometry, quality, scores)
%EXPORT_SCORES Save original and normalized metrics as a CSV table.

    csvFile = fullfile(cfg.outputDir, 'scores.csv');
    fileId = fopen(csvFile, 'w');
    assert(fileId > 0, 'Unable to open score CSV for writing.');
    closeFile = onCleanup(@() fclose(fileId)); %#ok<NASGU>

    fprintf(fileId, ['plan,pass,min_fold,min_offset_kinds,cost,' ...
        'snr_db,semblance,stack_correlation,velocity_pick_perturbation,' ...
        'quality,geometry,economics,total\n']);

    for iPlan = 1:numel(plans)
        fprintf(fileId, ...
            '%s,%d,%d,%d,%.0f,%.5f,%.5f,%.5f,%.1f,%.5f,%.5f,%.5f,%.5f\n', ...
            plans(iPlan).name, scores.pass(iPlan), ...
            geometry(iPlan).minFold, geometry(iPlan).minKinds, ...
            scores.cost(iPlan), quality(iPlan).meanSNRdB, ...
            quality(iPlan).meanSemblance, ...
            quality(iPlan).meanCorrelation, ...
            quality(iPlan).meanPickPerturbation, ...
            scores.qualityScore(iPlan), ...
            scores.geometryScore(iPlan), ...
            scores.costScore(iPlan), scores.score(iPlan));
    end
end
