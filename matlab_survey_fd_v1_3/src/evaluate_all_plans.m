function quality = evaluate_all_plans(cfg, model, plans, geometry, ...
    shotX, receiverX, cleanShots, noisyShots, time)
%EVALUATE_ALL_PLANS Evaluate data metrics after hard geometry checks.

    numPlans = numel(plans);
    blank = struct( ...
        'meanSNRdB', NaN, ...
        'meanSemblance', NaN, ...
        'meanCorrelation', NaN, ...
        'meanPickPerturbation', NaN, ...
        'snrByCMP', [], ...
        'semByCMP', [], ...
        'sample', []);

    quality = repmat(blank, 1, numPlans);

    for iPlan = 1:numPlans
        if ~geometry(iPlan).pass
            fprintf('[QUALITY] %s skipped (geometry gate).\n', ...
                plans(iPlan).name);
            continue;
        end

        fprintf('[QUALITY] Evaluating %-24s\n', plans(iPlan).name);
        quality(iPlan) = quality_metrics( ...
            cfg, model, plans(iPlan), shotX, receiverX, ...
            cleanShots, noisyShots, time);
    end
end
