function validate_acquisition(cfg, plans)
%VALIDATE_ACQUISITION 确认所有炮检点位于物理网格节点。
    x = [plans.sx, plans.rx];
    assert(all(isfinite(x)) && all(x >= cfg.x(1) & x <= cfg.x(end)), ...
        'Acquisition positions must be within the model.');
    assert(all(abs((x - cfg.x(1)) / cfg.dx - round((x - cfg.x(1)) / cfg.dx)) < 1e-7), ...
        'All acquisition positions must lie on grid nodes.');
    z = [cfg.sourceZ, cfg.receiverZ];
    assert(all(isfinite(z)) && all(z >= cfg.z(1) & z <= cfg.z(end)) && ...
        all(abs((z - cfg.z(1)) / cfg.dz - round((z - cfg.z(1)) / cfg.dz)) < 1e-7), ...
        'Source and receiver depths must lie on grid nodes.');
end
