function print_results(plans, geometry, quality, scores)
%PRINT_RESULTS Print an easy-to-read MATLAB Command Window summary.
%
% Infeasible candidates are shown with '--' instead of NaN and -Inf.

    separator = repmat('-', 1, 103);
    fprintf('\n%s\n', separator);
    fprintf('  ACQUISITION PLAN COMPARISON\n');
    fprintf('%s\n', separator);
    fprintf(['%-24s  %-4s %8s %8s %11s %8s %7s %7s %9s\n'], ...
        'Plan', 'Pass', 'MinFold', 'OffKinds', 'Cost', ...
        'SNR(dB)', 'Sem', 'Corr', 'Score');
    fprintf('%s\n', separator);

    for iPlan = 1:numel(plans)
        if scores.pass(iPlan)
            fprintf(['%-24s  %-4s %8d %8d %11.0f ' ...
                '%8.2f %7.2f %7.2f %9.3f\n'], ...
                plans(iPlan).name, 'YES', ...
                geometry(iPlan).minFold, geometry(iPlan).minKinds, ...
                scores.cost(iPlan), quality(iPlan).meanSNRdB, ...
                quality(iPlan).meanSemblance, ...
                quality(iPlan).meanCorrelation, scores.score(iPlan));
        else
            fprintf(['%-24s  %-4s %8d %8d %11.0f ' ...
                '%8s %7s %7s %9s\n'], ...
                plans(iPlan).name, 'NO', ...
                geometry(iPlan).minFold, geometry(iPlan).minKinds, ...
                scores.cost(iPlan), '--', '--', '--', '--');
        end
    end

    fprintf('%s\n', separator);
    if isempty(scores.winner)
        fprintf('  RESULT: No plan meets the hard constraints.\n');
    else
        best = scores.winner;
        fprintf('  WINNER: %-24s  TOTAL SCORE: %.3f\n', ...
            plans(best).name, scores.score(best));
    end
    fprintf('%s\n', separator);
end
